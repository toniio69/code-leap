<?php

// Regenerates the App\ entries in vendor/composer/autoload_classmap.php
// by scanning app/ for real class definitions (fixes stale paths after files moved).

$baseDir = dirname(__DIR__);
require $baseDir.'/scripts/regen_classmap_data.php';

// Splice into existing classmap file, replacing the App\..., Database\..., Tests\... entries.
$classmapPath = $baseDir.'/vendor/composer/autoload_classmap.php';
$contents = file_get_contents($classmapPath);

preg_match_all("/^\\s+'([^']+)'\\s*=>\\s*(.+?),\\s*$/m", $contents, $matches, PREG_SET_ORDER);
$existing = [];
foreach ($matches as $m) {
    if (preg_match('/^(App|Database|Tests)\\\\/', $m[1])) {
        continue;
    }
    $existing[$m[1]] = rtrim($m[2], ',');
}

$all = array_merge($existing, $map);
ksort($all);

$out = "<?php\n";
$out .= "// autoload_classmap.php @generated by Composer\n";
$out .= "\$vendorDir = dirname(__DIR__);\n";
$out .= "\$baseDir = dirname(\$vendorDir);\n\n";
$out .= "return array(\n";

foreach ($all as $class => $path) {
    $escapedClass = str_replace('\\', '\\\\', $class);
    if (isset($map[$class])) {
        $rel = str_replace('\\', '\\\\', $map[$class]);
        $out .= "    '".$escapedClass."' => \$baseDir . '/".$rel."',\n";
    } else {
        $out .= "    '".$escapedClass."' => ".$path.",\n";
    }
}
$out .= ");\n";
file_put_contents($classmapPath, $out);
echo 'Classmap regenerated: '.count($map).' app classes mapped.'.PHP_EOL;
